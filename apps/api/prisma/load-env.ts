import { config } from 'dotenv';

/**
 * بارگذاری متغیرهای محیطی برای اسکریپت‌های خط فرمان.
 *
 * ── چرا `import 'dotenv/config'` کافی نیست ──────────────────────────────
 * آن فقط `.env` کنار پوشه کاری را می‌خواند. اسکریپت‌های این بسته از
 * `apps/api` اجرا می‌شوند، ولی فایل `.env` پروژه در **ریشه مخزن** ساخته
 * می‌شود (راهنمای راه‌اندازی همان را می‌گوید). نتیجه: `pnpm db:migrate` و
 * `pnpm db:seed` با «DATABASE_URL تعریف نشده» شکست می‌خوردند، در حالی که
 * `pnpm dev` کار می‌کرد — چون NestJS خودش هر دو مسیر را می‌بیند.
 *
 * ترتیب اینجا عمداً همان ترتیب `envFilePath` در `app.module.ts` است:
 * `.env` محلی مقدم است تا بتوان تنظیمات یک بسته را جدا کرد، و ریشه
 * پیش‌فرض مشترک می‌ماند. در dotenv، فایل نخست برنده است.
 */
export function loadEnv(): void {
  config({ path: ['.env', '../../.env'], quiet: true });
}

loadEnv();
